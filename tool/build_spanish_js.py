#!/usr/bin/env python3
"""Writes the Spanish text for the guide's browser scripts from camino/locale/es.json.

    python tool/build_spanish_js.py            # rewrite the two files
    python tool/build_spanish_js.py --check    # change nothing; exit status 1 if they are out of date

camino/locale/es.json has three parts:
    "ui"    text built on the server (templates, titles, stage names). Read by Django directly.
    "js"    text for the scripts on every page (offline pack, update banner, search).
    "plan"  text for the planner page, including the stage names it shows.
The last two are copied into static files, because a script cannot read es.json:
    "js"    -> camino/static/camino/js/i18n-es.js        (every Spanish page)
    "plan"  -> camino/static/camino/js/i18n-es-plan.js   (the planner page only)
Edit es.json, run this script, and commit all three files. A test fails if they disagree.

Uses only the Python standard library.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOGUE = ROOT / 'camino' / 'locale' / 'es.json'
OUTPUTS = {
    'js': ROOT / 'camino' / 'static' / 'camino' / 'js' / 'i18n-es.js',
    'plan': ROOT / 'camino' / 'static' / 'camino' / 'js' / 'i18n-es-plan.js',
}
HEADER = (
    '/* %(name)s: GENERATED by tool/build_spanish_js.py from the "%(section)s" part of camino/locale/es.json.\n'
    ' * Do not edit by hand: change es.json and run the tool again. */\n'
)


def render(section, catalogue=None):
    """The text of the JavaScript file for one part of the catalogue."""
    if catalogue is None:
        catalogue = json.loads(CATALOGUE.read_text(encoding='utf-8'))
    table = catalogue.get(section, {})
    lines = []
    for key in sorted(table):
        # '<', '>' and '&' are escaped so the file is safe wherever it is loaded; the line separators
        # U+2028/2029 are escaped because older browsers treat them as line ends inside a string.
        value = json.dumps(table[key], ensure_ascii=False)
        for char, escape in (('<', '\\u003c'), ('>', '\\u003e'), ('&', '\\u0026'), (' ', '\\u2028'), (' ', '\\u2029')):
            value = value.replace(char, escape)
        lines.append('  %s: %s' % (json.dumps(key, ensure_ascii=False).replace('<', '\\u003c').replace('>', '\\u003e').replace('&', '\\u0026'), value))
    return (
        HEADER % {'name': OUTPUTS[section].name, 'section': section}
        + 'window.CAMINO_I18N = window.CAMINO_I18N || {};\n'
        + 'window.CAMINO_I18N.es = Object.assign(window.CAMINO_I18N.es || {}, {\n'
        + ',\n'.join(lines) + '\n'
        + '});\n'
    )


def main(argv):
    check = '--check' in argv
    catalogue = json.loads(CATALOGUE.read_text(encoding='utf-8'))
    stale = []
    for section, path in OUTPUTS.items():
        wanted = render(section, catalogue)
        current = path.read_bytes().decode('utf-8') if path.exists() else None
        if current is not None:
            current = current.replace('\r\n', '\n')   # a Windows checkout may have changed the line ends
        if current == wanted:
            print('up to date: %s' % path.relative_to(ROOT))
            continue
        stale.append(path)
        if check:
            print('OUT OF DATE: %s' % path.relative_to(ROOT))
        else:
            path.write_bytes(wanted.encode('utf-8'))
            print('written: %s (%d phrases)' % (path.relative_to(ROOT), len(catalogue.get(section, {}))))
    return 1 if (check and stale) else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
